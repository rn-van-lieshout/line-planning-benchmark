/**
 * Runs CGNSolver on one instance, then compares the routes generated by the
 * solver's B&P with the routes found by the CGNEvaluator on the same line plan.
 * Reports the percentage of evaluator routes that were not already in the
 * solver's route pool.
 */
public class RouteComparisonMain
{
	public static void main(String[] args) throws IOException, IloException
	{
		String dataFolder = "instances";

		// 0 = Randstad-IC, 1 = Randstad-IC-SPR, 2 = Nederland-IC, 3 = Nederland-IC-SPR,
		// 4 = SmallSwitzerland, 5 = Switzerland
		int instanceIndex = 5;
		String instanceFolder = dataFolder + "/" + switch (instanceIndex)
		{
		case 0 -> "Randstad-IC";
		case 1 -> "Randstad-IC-SPR";
		case 2 -> "Nederland-IC";
		case 3 -> "Nederland-IC-SPR";
		case 4 -> "SmallSwitzerland";
		case 5 -> "Switzerland";
		default -> throw new IllegalArgumentException("Unknown instance index: " + instanceIndex);
		};

		// 0 = raw, 1 = strategy1-split, 2 = strategy1-agg, 3 = strategy2-split,
		// 4 = strategy2-agg, 5 = strategy3-split, 6 = strategy3-agg
		int odMatrixIndex = 0;
		String odMatrixVariant = switch (odMatrixIndex)
		{
		case 0 -> "0";
		case 1 -> "1-false";
		case 2 -> "1-true";
		case 3 -> "2-false";
		case 4 -> "2-true";
		case 5 -> "3-false";
		case 6 -> "3-true";
		default -> throw new IllegalArgumentException("Unknown OD matrix index: " + odMatrixIndex);
		};
		String odMatrixFile = instanceFolder + "/ODMatrix/" + odMatrixVariant + ".txt";

		// 0 = small, 1 = medium, 2 = large
		int transferPenaltyIndex = 1;
		String transferPenaltyVariant = switch (transferPenaltyIndex)
		{
		case 0 -> "small";
		case 1 -> "medium";
		case 2 -> "large";
		default -> throw new IllegalArgumentException("Unknown transfer penalty index: " + transferPenaltyIndex);
		};
		String transferPenaltyFile = instanceFolder + "/transferPenalty/" + transferPenaltyVariant + ".txt";

		int budgetIndex = 1;
		String budgetVariant = switch (budgetIndex)
		{
		case 0 -> "small";
		case 1 -> "medium";
		case 2 -> "large";
		default -> throw new IllegalArgumentException("Unknown budget index: " + budgetIndex);
		};

		int fixedCostIndex = 1;
		String budgetFolder = switch (fixedCostIndex)
		{
		case 0 -> "budget-fixedCost-low";
		case 1 -> "budget";
		case 2 -> "budget-fixedCost-high";
		default -> throw new IllegalArgumentException("Unknown fixed cost index: " + fixedCostIndex);
		};
		String budgetFile = instanceFolder + "/" + budgetFolder + "/" + budgetVariant + ".txt";

		String fixedCostVariant = switch (fixedCostIndex)
		{
		case 0 -> "low";
		case 1 -> "medium";
		case 2 -> "high";
		default -> throw new IllegalArgumentException("Unknown fixed cost index: " + fixedCostIndex);
		};
		String fixedCostFile = instanceFolder + "/fixedCost/" + fixedCostVariant + ".txt";

		int lineGenerationIndex = 0;
		String lineGenerationVariant = switch (lineGenerationIndex)
		{
		case 0 -> "small";
		case 1 -> "medium";
		case 2 -> "large";
		default -> throw new IllegalArgumentException("Unknown line generation index: " + lineGenerationIndex);
		};

		double demandScalar = 1.0;

		Configuration.initialiseConfiguration("settings.properties");

		LinePlanningInstance instance = new LinePlanningInstance(instanceFolder, odMatrixFile, budgetFile,
				transferPenaltyFile, demandScalar);
		instance.setLineGenerationFile(instanceFolder + "/LineGeneration/" + lineGenerationVariant + ".txt");

		LinePoolGenerator lpGen = new LinePoolGenerator(instance);
		List<Line> linePool = lpGen.getLines();
		instance.setLinePool(linePool);

		instance.setFixedCostFile(fixedCostFile);
		LinePlanningParameters.LINE_ACTIVATION_COST = Reader.readInt(fixedCostFile);

		// 0 = PTN, 1 = PTN+Karbstein, 2 = PTN+Benders, 3 = DPTN-MIP, 4 = DPTN-B&P, 5 = CGN
		int solverIndex = 1;
		String routeGenerationVariant = "large"; // used for solvers 0-3
		Solver solver = switch (solverIndex)
		{
		case 0 -> new PTNSolver(false);
		case 1 -> new PTNSolver(true);
		case 2 -> new PTNBendersSolver();
		case 3 -> new DPTNSolver(false);
		case 4 -> new DPTNSolver(true);
		case 5 -> new CGNSolver();
		default -> throw new IllegalArgumentException("Unknown solver index: " + solverIndex);
		};
		if (solverIndex < 4)
			instance.setRouteGenerationFile(instanceFolder + "/RouteGeneration/" + routeGenerationVariant + ".txt");

		boolean useStrongInequalities = false;
		solver.setUseStrongInequalities(useStrongInequalities);
		solver.setPairsPerGroup(1);

		int cpuTimeSeconds = 120;
		System.out.println("Calling solver: " + solver.getName());
		LinePlanningSolution solution = solver.solve(instance, linePool, cpuTimeSeconds);
		if (solution == null)
			solution = LinePlanningSolution.noSolution(instance);

		solution.evaluateTrueObjective();
		solution.printToConsole();

		RouteGenerator rpGen = null;
		if (instance.getRouteGenerationFile() != null)
		{
			rpGen = new RouteGenerator(instance, instance.getRouteGenerationFile());
			for (ODPair od : instance.getODPairs())
				rpGen.getRoutes(od, true);
		}
		compareRoutes(solver, solution, rpGen);
	}

	private static void compareRoutes(Solver solver, LinePlanningSolution solution, RouteGenerator rpGen)
	{
		LinePlanningSolution evalSolution = solution.getReoptimizedSolution();
		if (evalSolution == null)
		{
			System.out.println("No evaluator solution available (infeasible?).");
			return;
		}

		// Build connection-path signatures for the solver's pre-generated pool
		Set<List<Connection>> solverPaths = new HashSet<>();
		for (Route r : solver.getPreGeneratedRoutes())
			solverPaths.add(getConnectionPath(r));

		// Shortest path duration per OD pair (for detour computation)
		Map<ODPair, Double> shortestPaths = rpGen != null ? rpGen.getShortestPathDurations() : new HashMap<>();

		// Analyse evaluator routes: group new ones by nr of transfers
		int totalEval = 0;
		Map<Integer, List<Double>> newByTransfers = new TreeMap<>();
		double worstDetour = Double.MAX_VALUE;
		Route worstRoute = null;
		ODPair worstOD = null;
		double worstShortest = 0;
		for (Map.Entry<ODPair, Map<Route, Double>> entry : evalSolution.getRouteMap().entrySet())
		{
			ODPair od = entry.getKey();
			for (Route r : entry.getValue().keySet())
			{
				totalEval++;
				if (!solverPaths.contains(getConnectionPath(r)))
				{
					double shortest = shortestPaths.getOrDefault(od, 0.0);
					double detour = r.getDuration() - shortest;
					newByTransfers.computeIfAbsent(r.getNrTransfers(), k -> new ArrayList<>()).add(detour);
					if (detour < worstDetour)
					{
						worstDetour = detour;
						worstRoute = r;
						worstOD = od;
						worstShortest = shortest;
					}
				}
			}
		}

		int newCount = newByTransfers.values().stream().mapToInt(List::size).sum();
		System.out.println();
		System.out.println("=== Route comparison: solver pool vs CGN evaluator ===");
		System.out.printf("Solver pre-generated route pool:  %d routes%n", solver.getPreGeneratedRoutes().size());
		System.out.printf("Evaluator solution routes:        %d routes%n", totalEval);
		System.out.printf("Routes new to evaluator:          %d (%.1f%% of evaluator routes)%n",
				newCount, totalEval == 0 ? 0.0 : 100.0 * newCount / totalEval);

		if (!newByTransfers.isEmpty())
		{
			System.out.println();
			System.out.println("New routes breakdown by number of transfers:");
			for (Map.Entry<Integer, List<Double>> e : newByTransfers.entrySet())
			{
				List<Double> detours = e.getValue();
				double min = detours.stream().mapToDouble(Double::doubleValue).min().orElse(0);
				double max = detours.stream().mapToDouble(Double::doubleValue).max().orElse(0);
				double avg = detours.stream().mapToDouble(Double::doubleValue).average().orElse(0);
				System.out.printf("  %d transfer(s): %d routes,  detour min=%.1f  max=%.1f  avg=%.1f min%n",
						e.getKey(), detours.size(), min, max, avg);
			}

			if (worstRoute != null)
			{
				System.out.println();
				System.out.printf("Most negative detour: %.1f min (route duration=%.1f, shortest=%.1f)%n",
						worstDetour, worstRoute.getDuration(), worstShortest);
				System.out.printf("  OD: %s -> %s  transfers=%d%n",
						worstOD.getOrigin(), worstOD.getDestination(), worstRoute.getNrTransfers());
				System.out.printf("  Connection path: %s%n", getConnectionPath(worstRoute));

				if (rpGen != null)
				{
					List<DPTNRoute> odRoutes = rpGen.getRoutes(worstOD, false);
					System.out.printf("  RouteGenerator routes for this OD (%d total):%n", odRoutes.size());
					for (DPTNRoute r : odRoutes)
						System.out.printf("    duration=%.1f  transfers=%d  path=%s%n",
								r.getDuration(), r.getNrTransfers(), r.getConnectionPath());
				}
			}
		}
	}

	private static List<Connection> getConnectionPath(Route route)
	{
		if (route instanceof DPTNRoute)
			return ((DPTNRoute) route).getConnectionPath();
		List<Connection> path = new ArrayList<>();
		for (NetworkArc arc : route.getArcs())
		{
			if (arc instanceof Connection)
				path.add((Connection) arc);
			else if (arc instanceof CGNTravelArc)
				path.add(((CGNTravelArc) arc).getLineSegment());
		}
		return path;
	}
}
